package commands

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/kombifyio/stackkits/internal/actionableerror"
	"github.com/spf13/cobra"
)

var troubleshootingOutput string
var troubleshootingCheck bool

var docsEmitTroubleshootingCmd = &cobra.Command{
	Use: "emit-troubleshooting", Short: "Generate the shared standalone troubleshooting authority",
	Long:        "Generate stable error IDs, causes and recovery actions from the same authority used by CLI failures and MCP self-check. With --check, refuse missing or stale documentation without writing.",
	Args:        cobra.NoArgs,
	Annotations: map[string]string{noDeployObservabilityAnnotation: "true"},
	RunE: func(cmd *cobra.Command, _ []string) error {
		var out bytes.Buffer
		out.WriteString("# Standalone troubleshooting\n\nGenerated by `stackkit docs emit-troubleshooting`. Do not edit this projection.\n\n")
		out.WriteString("The [actionable-error authority](../internal/actionableerror/diagnostics.go) owns lifecycle diagnoses and consumes the existing [runtime taxonomy](../internal/applyoutcome/classes.go). CLI failures, `stackkit agent diagnose <error-id>` and the MCP `stackkit_self_check_plan` use those same contracts. A guidance lookup is not a health observation.\n\n")
		out.WriteString("Keep the original workspace, Owner custody and saved choices when resuming. Use `stackkit -C <workspace>` from another directory. Inspect `stackkit logs latest --json` and use `stackkit support export --help` for bounded redacted evidence. Standard Mode is account-free; Advanced operations require Techstack dispatch.\n\n")
		out.WriteString("Recorded failures in [CHANGELOG](../CHANGELOG.md):\n\n")
		for _, failure := range actionableerror.RecordedFailures() {
			fmt.Fprintf(&out, "- %s: `%s`.\n", failure.Failure, strings.Join(failure.Reasons, "`, `"))
		}
		out.WriteString("\nA missing managed Origin CA certificate is a typed degraded completion; Standard/custom-domain issuance still fails on its actual TLS error.\n\n")
		out.WriteString("| Error ID | One-line cause | Next action | Retry after correction |\n| --- | --- | --- | --- |\n")
		escape := func(value string) string { return strings.ReplaceAll(strings.ReplaceAll(value, "|", "\\|"), "\n", " ") }
		for _, detail := range actionableerror.Diagnostics() {
			fmt.Fprintf(&out, "| `%s` | %s | %s | %t |\n", detail.ReasonCode, escape(detail.Message), escape(strings.Join(detail.UserGuidance, " ")), detail.Retryable)
		}
		out.WriteString("\nFor ACME rate limits, preserve the observed authority's `retryAfter` (RFC 3339 UTC); never invent an earlier retry time. Changing servers while requesting the same address does not reset the duplicate-certificate limit. HTTP 526 describes failed origin TLS; inspect the actual certificate diagnostic before selecting a remedy. Do not bypass TLS, change trust roots or weaken signed recovery admission.\n")
		path := resolvePathFromWorkDir(getWorkDir(), troubleshootingOutput)
		if troubleshootingCheck {
			current, err := os.ReadFile(path)
			if err != nil {
				return err
			}
			if !bytes.Equal(current, out.Bytes()) {
				return fmt.Errorf("troubleshooting projection is stale; run stackkit docs emit-troubleshooting")
			}
			return nil
		}
		if err := os.MkdirAll(filepath.Dir(path), 0755); err != nil {
			return err
		}
		return os.WriteFile(path, out.Bytes(), 0644)
	},
}

func init() {
	docsEmitTroubleshootingCmd.Flags().StringVar(&troubleshootingOutput, "out", "docs/TROUBLESHOOTING.md", "Output path, relative to --chdir")
	docsEmitTroubleshootingCmd.Flags().BoolVar(&troubleshootingCheck, "check", false, "Write nothing; fail when the generated guide differs")
	docsCmd.AddCommand(docsEmitTroubleshootingCmd)
}
