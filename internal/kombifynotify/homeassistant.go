package kombifynotify

import (
	"net/netip"
	"strconv"
	"strings"
)

const (
	// RequestPath is the agent route Home Assistant posts to.
	RequestPath = "/v1/user-notifications"
	// SecretKey is the secrets.yaml key that holds the Authorization header.
	SecretKey = "kombify_notify_authorization"
)

// HomeAssistantPlatformYAML is the notify platform file for the gateway
// address. It names no secret: the Authorization header is a !secret
// reference that Home Assistant resolves from the secrets.yaml beside this
// file.
//
// Home Assistant's REST notify sends {"text": <message>} and merges only the
// platform's own data_template, never a service call's data, so the template
// forwards exactly two author-set fields. The audience is "member" whenever a
// target is given (the target becomes member_username), the author's
// audience otherwise, and "me" when neither is set.
func HomeAssistantPlatformYAML(gateway netip.Addr) (string, error) {
	listen, err := ListenAddress(gateway)
	if err != nil {
		return "", err
	}
	var body strings.Builder
	body.WriteString("# StackKits-owned kombify notify target. Regenerated by stackkit apply.\n")
	body.WriteString("- platform: rest\n")
	body.WriteString("  name: kombify\n")
	body.WriteString("  resource: http://" + listen + RequestPath + "\n")
	body.WriteString("  method: POST_JSON\n")
	body.WriteString("  message_param_name: text\n")
	body.WriteString("  target_param_name: member_username\n")
	body.WriteString("  headers:\n")
	body.WriteString("    Authorization: !secret " + SecretKey + "\n")
	body.WriteString("  data_template:\n")
	body.WriteString(`    automation_id: "{{ data.get('automation_id', '') if data else '' }}"` + "\n")
	body.WriteString(`    audience: "{{ 'member' if target is defined else ((data.get('audience') or 'me') if data else 'me') }}"` + "\n")
	return body.String(), nil
}

// HomeAssistantSecretsYAML is the secrets file beside the platform file. It is
// the one generated artifact besides the token file that holds the secret and
// is persisted owner-only; Home Assistant resolves the nearest secrets.yaml
// from the including file's directory upward, so the owner's own
// /config/secrets.yaml stays untouched.
func HomeAssistantSecretsYAML(token string) string {
	return SecretKey + ": " + strconv.Quote("Bearer "+token) + "\n"
}
