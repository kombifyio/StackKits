package main

import (
	"bytes"
	"fmt"
	"go/format"
	"path/filepath"
	"sort"

	"github.com/google/go-containerregistry/pkg/name"
	skcue "github.com/kombifyio/stackkits/internal/cue"
)

// componentReleaseTracksOutput is the generated resolvedplan table of the
// modules whose entry image follows a "patch" release track.
const componentReleaseTracksOutput = "internal/resolvedplan/component_release_tracks_gen.go"

// writeEntryReleases projects every catalog module's entry component into
// the renderer table workloadEntryReleases: its default pin first, then each
// release the catalog has tested (#ModuleRuntimeComponentV2.releases). Only
// an entry component may list releases. A module whose entry image has no
// exact release tag admits no override. Internal-only modules keep their own
// governed image selection and are not listed.
func writeEntryReleases(out *bytes.Buffer, modules []catalogRendererModule, include func(string) bool) error {
	sorted := append([]catalogRendererModule(nil), modules...)
	sort.Slice(sorted, func(i, j int) bool { return sorted[i].Metadata.ID < sorted[j].Metadata.ID })
	for _, module := range sorted {
		if !include(module.Metadata.ID) {
			continue
		}
		entryRef := module.Runtime.EntryComponentRef
		var entry *catalogRendererComponent
		for index := range module.Runtime.Components {
			component := &module.Runtime.Components[index]
			if component.ID == entryRef {
				entry = component
			} else if len(component.Releases) > 0 {
				return fmt.Errorf("module %q admits further releases only on its entry component", module.Metadata.ID)
			}
		}
		if entryRef == "" || entry == nil {
			continue
		}
		defaultRelease, err := pinnedImageRelease(entry.Image)
		if err != nil {
			if len(entry.Releases) > 0 {
				return fmt.Errorf("module %q entry image: %w", module.Metadata.ID, err)
			}
			continue
		}
		fmt.Fprintf(out, "\t%q: {Component: %q, Images: []workloadReleaseImage{\n", module.Metadata.ID, entry.ID)
		fmt.Fprintf(out, "\t\t{Release: %q, Ref: %q, Digest: %q},\n", defaultRelease, entry.Image.Ref, entry.Image.Digest)
		seen := map[string]bool{defaultRelease: true}
		for _, admitted := range entry.Releases {
			release, err := pinnedImageRelease(admitted.Image)
			if err != nil {
				return fmt.Errorf("module %q tested release: %w", module.Metadata.ID, err)
			}
			if seen[release] {
				return fmt.Errorf("module %q admits release %q twice", module.Metadata.ID, release)
			}
			seen[release] = true
			fmt.Fprintf(out, "\t\t{Release: %q, Ref: %q, Digest: %q},\n", release, admitted.Image.Ref, admitted.Image.Digest)
		}
		out.WriteString("\t}},\n")
	}
	return nil
}

// writeComponentReleaseTracks projects each module's upstream.track
// (modules/<slug>/module.cue, the one authoring source the Watch feed reads
// too) onto the catalog module whose entry image is the same repository.
// Only "patch" is written; every other module follows "minor", and a major
// release moves only with a StackKits release.
func writeComponentReleaseTracks(repoRoot string, modules []catalogRendererModule, include func(string) bool) error {
	contracts, err := skcue.NewModuleReader().ReadAllModules(filepath.Join(repoRoot, "modules"))
	if err != nil {
		return fmt.Errorf("read module upstream tracks: %w", err)
	}
	tracks := map[string]string{}
	for _, contract := range contracts {
		for _, service := range contract.Services {
			repository, err := name.NewRepository(service.Image)
			if err != nil || service.Upstream == nil {
				continue
			}
			// The narrower track wins where two modules declare one image.
			if tracks[repository.Name()] != "patch" {
				tracks[repository.Name()] = service.Upstream.Track
			}
		}
	}
	patch := []string{}
	for _, module := range modules {
		if !include(module.Metadata.ID) {
			continue
		}
		for _, component := range module.Runtime.Components {
			if component.ID != module.Runtime.EntryComponentRef || module.Runtime.EntryComponentRef == "" {
				continue
			}
			reference, err := name.ParseReference(component.Image.Ref)
			if err == nil && tracks[reference.Context().Name()] == "patch" {
				patch = append(patch, module.Metadata.ID)
			}
		}
	}
	sort.Strings(patch)
	var source bytes.Buffer
	source.WriteString("// Code generated by architecture-v2 bundlegen from modules/*/module.cue upstream.track; DO NOT EDIT.\n\n")
	source.WriteString("package resolvedplan\n\n")
	source.WriteString("// componentReleaseTracks names the catalog modules whose entry image follows\n// a \"patch\" release track; every other module follows \"minor\".\n")
	source.WriteString("var componentReleaseTracks = map[string]string{\n")
	for _, moduleID := range patch {
		fmt.Fprintf(&source, "\t%q: \"patch\",\n", moduleID)
	}
	source.WriteString("}\n")
	formatted, err := format.Source(source.Bytes())
	if err != nil {
		return fmt.Errorf("format generated component release tracks: %w", err)
	}
	return writeProjectedSource(repoRoot, componentReleaseTracksOutput, formatted)
}
